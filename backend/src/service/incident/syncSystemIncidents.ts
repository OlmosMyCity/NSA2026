/**
 * @module service/incident/syncSystemIncidents
 * System-incident synchronization helpers translating deterministic medical evaluations and
 * live radiation telemetry states into deduplicated `OpenIncidentUseCase` invocations.
 *
 * Note: `INDICATOR_LABELS` and incident titles/descriptions are preserved in Spanish for
 * operational UI and unit-test contracts.
 */

import { Incident, IncidentCategory, IncidentSeverity } from "@prisma/client";
import { RadiationEngineState } from "../radiation/engine/index.js";
import { HealthAlert, HealthEvaluationResult } from "../health/evaluateReading.js";
import { OpenIncidentUseCase } from "./OpenIncidentUseCase.js";

const INDICATOR_LABELS: Record<string, string> = {
  heartRate: "Heart rate",
  bloodPressure: "Blood pressure",
  glucose: "Blood glucose",
  temperature: "Body temperature",
  spo2: "O2 saturation (SpO2)",
  sleep: "Sleep duration",
  mood: "Mood",
};

function mapAlertSeverity(level: HealthAlert["level"]): IncidentSeverity {
  return level === "CRITICAL" ? IncidentSeverity.CRITICAL : IncidentSeverity.WARNING;
}

/**
 * Opens or escalates deduplicated `MEDICAL` incidents for each alert generated by
 * `evaluateReading`, scoped to the affected `astronautId` and linked to `readingId`.
 */
export async function openMedicalIncidentsFromReading(
  openIncidentUseCase: OpenIncidentUseCase,
  astronautId: string,
  readingId: string,
  evaluation: HealthEvaluationResult
): Promise<Incident[]> {
  if (evaluation.alerts.length === 0) {
    return [];
  }

  const results: Incident[] = [];
  for (const alert of evaluation.alerts) {
    const label = INDICATOR_LABELS[alert.indicator] ?? alert.indicator;
    const { incident } = await openIncidentUseCase.execute({
      category: IncidentCategory.MEDICAL,
      type: alert.indicator,
      severity: mapAlertSeverity(alert.level),
      title: `Medical alert (${alert.level}): ${label}`,
      description: alert.message,
      astronautId,
      source: "HEALTH_READING",
      readingId,
      protocolId: alert.protocolId,
      metadata: {
        indicator: alert.indicator,
        protocolId: alert.protocolId,
        value: alert.value,
        readingStatus: evaluation.status,
      },
    });
    results.push(incident);
  }

  return results;
}

/**
 * Opens or escalates a global (`astronautId: null`) `RADIATION` incident (`SOLAR_RADIATION_STORM`)
 * whenever `RadiationEngineState.currentTelemetry.stormScale` is `S1_MINOR` or higher.
 * Returns `null` when space weather is nominal (`S0_NOMINAL`).
 */
export async function openRadiationIncidentFromState(
  openIncidentUseCase: OpenIncidentUseCase,
  state: RadiationEngineState
): Promise<Incident | null> {
  const stormScale = state.currentTelemetry.stormScale;
  if (stormScale === "S0_NOMINAL") {
    return null;
  }

  const severity =
    stormScale === "S1_MINOR" ? IncidentSeverity.WARNING : IncidentSeverity.CRITICAL;

  const descriptionParts = [
    state.earlyWarning.triggerEvent,
    state.mitigation.abortEvaImmediately ? "Abort EVA immediately." : null,
    state.mitigation.evacuateToStormShelter ? "Evacuate to storm shelter." : null,
  ].filter(Boolean);

  const { incident } = await openIncidentUseCase.execute({
    category: IncidentCategory.RADIATION,
    type: "SOLAR_RADIATION_STORM",
    severity,
    title: `Solar radiation storm (${stormScale})`,
    description:
      descriptionParts.length > 0
        ? descriptionParts.join(" ")
        : `Solar storm level ${stormScale} detected by the radiation engine.`,
    astronautId: null,
    source: "RADIATION_ENGINE",
    metadata: {
      stormScale,
      isSimulated: state.isSimulated,
      abortEvaImmediately: state.mitigation.abortEvaImmediately,
      evacuateToStormShelter: state.mitigation.evacuateToStormShelter,
      powerDownExternalSensors: state.mitigation.powerDownExternalSensors,
    },
  });

  return incident;
}
